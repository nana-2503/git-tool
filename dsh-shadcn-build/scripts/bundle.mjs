/**
 * Bundle the Client half into the browser module-table artifact.
 *
 * The output is the format the Harness client-modules loader expects:
 *   window.__ModuleLoader__.load({ id, factory(require) { … } })
 * with `react`, `react-dom` and `react/jsx-runtime` left as `require()` calls,
 * because the shell seeds them in `PLATFORM_MODULES`. Everything else — Base UI,
 * cva, `cn`, lucide, the vendored ui/ source and the compiled stylesheet — is
 * inlined, so the plugin ships as one file with no dependencies to install.
 *
 * Run with: npm run bundle   (after `npm run css`)
 */
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const OUT = '/root/dsh-github-push/client.js';

/** Must equal the bundle package name: the module table keys factories by it. */
const MODULE_ID = '@local/dsh-github-push';

const result = await build({
  entryPoints: [join(root, 'src', 'plugin.jsx')],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: ['chrome120', 'firefox120', 'safari17'],
  jsx: 'automatic',
  external: ['react', 'react-dom', 'react/jsx-runtime', 'react-dom/client'],
  loader: { '.css': 'text' },
  define: { 'process.env.NODE_ENV': '"production"' },
  minify: true,
  legalComments: 'none',
  write: false,
  logLevel: 'warning',
});

const code = result.outputFiles[0].text;

const banner = `/**
 * @local/dsh-github-push — Client half. Generated by dsh-shadcn-build; do not edit.
 *
 * Wraps the official shadcn components (registry/bases/base/ui, style vega) with
 * the Token values of the DeepSeek Harness theme, and exposes them through the
 * browser module table.
 */`;

const artifact = `${banner}
window.__ModuleLoader__.load({
  id: ${JSON.stringify(MODULE_ID)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${code}
    return module.exports.default !== undefined ? module.exports.default : module.exports;
  },
});
`;

writeFileSync(OUT, artifact);
const css = readFileSync(join(root, 'dist', 'shadcn.css'), 'utf8');
console.log(`bundle ${(artifact.length / 1024).toFixed(0)} KiB written to ${OUT}`);
console.log(`  (inlined stylesheet: ${(css.length / 1024).toFixed(0)} KiB, inlined ui/: Base UI + cva + cn + lucide)`);
console.log(`  external requires: react, react-dom, react/jsx-runtime`);